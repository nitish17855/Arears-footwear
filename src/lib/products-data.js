export function generateInitialVariants() {
  const variants = [];
  INITIAL_PRODUCTS.forEach(product => {
    product.colorways.forEach(color => {
      product.sizes.forEach(size => {
        const hash = (product.id.length * 13 + color.name.length * 7 + Math.floor(size * 10)) % 15;
        const stockQuantity = 4 + hash;
        variants.push({
          id: `var-${product.slug}-${color.name.toLowerCase().replace(/\s+/g, '-')}-${size}`,
          productId: product.id,
          productSlug: product.slug,
          productName: product.name,
          colorName: color.name,
          colorHex: color.primaryHex,
          secondaryHex: color.secondaryHex,
          size: size,
          sku: `ARR-${product.slug.slice(0, 3).toUpperCase()}-${color.name.slice(0, 3).toUpperCase()}-${size * 10}`,
          stockQuantity: stockQuantity,
          basePrice: product.basePrice,
          image: color.image || product.image
        });
      });
    });
  });
  return variants;
}
